#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.join(__dirname, '..');
const JSONL_PATH = path.join(ROOT_DIR, 'logs', 'app-errors.jsonl');

const args = process.argv.slice(2);

// Check flags
if (args.includes('--clear')) {
  try {
    fs.writeFileSync(JSONL_PATH, '', 'utf8');
    const humanPath = path.join(ROOT_DIR, 'logs', 'app-errors.log');
    fs.writeFileSync(humanPath, `[${new Date().toISOString()}] Error logs cleared by Error Doctor.\n`, 'utf8');
    console.log('✅ تمامی لاگ‌های خطای پروژه با موفقیت پاکسازی شدند.');
    process.exit(0);
  } catch (err) {
    console.error('❌ خطا در پاکسازی لاگ‌ها:', err.message);
    process.exit(1);
  }
}

if (args.includes('--test')) {
  try {
    const testEntry = {
      id: 'test-' + Date.now(),
      timestamp: new Date().toISOString(),
      source: 'backend',
      type: 'testError',
      message: 'Test simulated error generated by Error Doctor CLI',
      stack: 'Error: Test simulated error\n    at testError (scripts/error-doctor.js:33:11)',
      route: '/api/test/doctor',
      method: 'GET',
      statusCode: 500,
      clientInfo: null,
      meta: { simulated: true },
      status: 'open',
    };
    fs.appendFileSync(JSONL_PATH, JSON.stringify(testEntry) + '\n', 'utf8');
    console.log('🧪 یک خطای تستی با موفقیت در لاگ ثبت شد.');
    process.exit(0);
  } catch (err) {
    console.error('❌ خطا در ثبت خطای تستی:', err.message);
    process.exit(1);
  }
}

console.log('\n======================================================');
console.log('🩺 دستیار هوشمند عیب‌یابی و پایش خطاهای آیه پلاس (Error Doctor)');
console.log('======================================================\n');

if (!fs.existsSync(JSONL_PATH)) {
  console.log('🎉 هیچ فایل لاگی وجود ندارد و سیستم کاملاً سالم است.');
  process.exit(0);
}

const content = fs.readFileSync(JSONL_PATH, 'utf8');
const lines = content.trim().split('\n').filter(Boolean);

if (lines.length === 0) {
  console.log('✨ تبریک! هیچ خطایی در سیستم ثبت نشده است (Logs are clean).\n');
  process.exit(0);
}

const errors = lines
  .map((l) => {
    try {
      return JSON.parse(l);
    } catch {
      return null;
    }
  })
  .filter(Boolean);

const backendCount = errors.filter((e) => e.source === 'backend').length;
const frontendCount = errors.filter((e) => e.source === 'frontend').length;

console.log(`📊 آمار کلی خطاها:`);
console.log(`   • مجموع خطاهای ثبت‌شده: ${errors.length}`);
console.log(`   • خطاهای سمت بک‌اند (Backend): ${backendCount}`);
console.log(`   • خطاهای سمت فرانت‌اند (Frontend): ${frontendCount}`);
console.log('\n------------------------------------------------------\n');

// Group recurring messages
const grouped = new Map();
errors.forEach((e) => {
  const key = `${e.source}:${e.type}:${e.message.slice(0, 80)}`;
  if (!grouped.has(key)) {
    grouped.set(key, { ...e, occurrences: 0 });
  }
  grouped.get(key).occurrences += 1;
});

const sortedIssues = [...grouped.values()].sort((a, b) => b.occurrences - a.occurrences);

console.log(`🔍 تحلیل و تشخیص علل ریشه‌ای خطاها (${sortedIssues.length} مورد یکتا):\n`);

sortedIssues.forEach((issue, index) => {
  const num = index + 1;
  const badge = issue.source === 'backend' ? '🖥️  [BACKEND]' : '🌐 [FRONTEND]';
  console.log(`\x1b[1m${num}. ${badge} ${issue.type} (${issue.occurrences} مرتبه تکرار)\x1b[0m`);
  console.log(`   🕒 آخرین وقوع: ${issue.timestamp}`);
  if (issue.route) console.log(`   📍 مسیر / روت: ${issue.route}`);
  console.log(`   💬 پیام خطا: \x1b[31m${issue.message}\x1b[0m`);

  // Extract file location from stack if present
  const matchFile = issue.stack.match(/(?:file:\/\/)?(\/[^:\n\r]+):(\d+):(\d+)/) ||
    issue.stack.match(/\bat\s+.*?\((.*?):(\d+):(\d+)\)/);
  if (matchFile) {
    let relPath = matchFile[1].replace(ROOT_DIR + '/', '');
    console.log(`   📁 فایل و سطر مربوطه: \x1b[33m${relPath}:${matchFile[2]}\x1b[0m`);

    // Preview code snippet if file exists
    const fullFilePath = path.resolve(ROOT_DIR, relPath);
    if (fs.existsSync(fullFilePath)) {
      try {
        const fileLines = fs.readFileSync(fullFilePath, 'utf8').split('\n');
        const lineNum = parseInt(matchFile[2], 10);
        const start = Math.max(0, lineNum - 2);
        const end = Math.min(fileLines.length, lineNum + 2);
        console.log('   📄 زمینه کد در فایل:');
        for (let i = start; i < end; i++) {
          const prefix = i + 1 === lineNum ? '   👉' : '     ';
          console.log(`   ${prefix} ${i + 1}: ${fileLines[i]}`);
        }
      } catch {}
    }
  }

  // Recommended smart fix
  console.log('   💡 \x1b[32mراهنمای رفع خطا توسط دستیار:\x1b[0m');
  const msg = issue.message;
  if (msg.includes('is missing') || msg.includes('PrismaClientValidationError')) {
    console.log('      - بررسی فیلدهای ارسالی در درخواست: یک فیلد اجباری ارسال نشده است.');
    console.log('      - فیلد را در کامپوننت فرانت‌اند یا لایه filterModelFields در server/routes/entities.js مپ کنید.');
  } else if (msg.includes('is not defined')) {
    console.log('      - نام متغیر یا تابع را بررسی کنید؛ این متغیر در محدوده کد ایمپورت یا اعلان نشده است.');
  } else if (msg.includes('Cannot read properties of undefined') || msg.includes('Cannot read property of null')) {
    console.log('      - از Optional Chaining (?.) برای خواندن فیلد استفاده کنید تا در صورت خالی بودن داده کرش رخ ندهد.');
  } else {
    console.log('      - جزئیات Stack Trace را بررسی کنید و از try/catch برای مهار خطا استفاده نمایید.');
  }

  console.log('\n------------------------------------------------------\n');
});

console.log('💡 دستورات مفید:');
console.log('   • پاکسازی لاگ‌ها:   npm run doctor -- --clear');
console.log('   • ارسال خطای آزمایشی: npm run doctor -- --test\n');
