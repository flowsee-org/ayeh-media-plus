// Intelligent mood detector from prompt text
function detectMoodCategory(prompt = '') {
  const p = prompt.toLowerCase();
  for (const [category, data] of Object.entries(MOOD_DATABASE)) {
    if (data.matchKeywords.some((kw) => p.includes(kw))) {
      return data;
    }
  }
  // Default to anxiety / peace companion if no specific match
  return MOOD_DATABASE.anxiety;
}

// Quranic fallback generator if external AI API keys are not provided
function generateFallbackResponse(prompt = '', schema) {
  const isVerseGuide = prompt.includes('VerseGuide') || (schema?.properties && 'verses' in schema.properties && 'understanding' in schema.properties);

  const matched = detectMoodCategory(prompt);

  if (isVerseGuide) {
    return {
      understanding: matched.empathy,
      caption: 'هدایت قرآنی برای آرامش دل و استقامت در زندگی',
      verses: matched.verses.map((v) => ({
        verse_key: v.verse_key,
        why: v.why,
        action: v.action,
        visual: 'نور خورشید در میان ابرهای بهاری و زلالی آب روان',
      })),
    };
  }

  // Assistant structured companion response
  return {
    empathy: matched.empathy,
    verses: matched.verses,
    closing: matched.closing,
  };
}

// POST /api/integrations/llm
router.post('/llm', async (req, res) => {
  try {
    const { prompt, response_json_schema } = req.body;

    const openaiKey = process.env.OPENAI_API_KEY;
    const geminiKey = process.env.GEMINI_API_KEY;

    if (openaiKey) {
      try {
        const response = await fetch('https://api.openai.com/v1/chat/completions', {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            Authorization: `Bearer ${openaiKey}`,
          },
          body: JSON.stringify({
            model: 'gpt-4o-mini',
            messages: [
              {
                role: 'system',
                content:
                  'You are a compassionate Quranic reflection companion (همدم قرآنی و تدبّر). Always respond in authentic Persian with empathy, real Quranic verses, Arabic text, translation, why this verse applies, and practical daily actions. Respond in valid JSON matching the requested schema.',
              },
              { role: 'user', content: prompt },
            ],
            response_format: { type: 'json_object' },
            temperature: 0.6,
          }),
        });

        if (response.ok) {
          const data = await response.json();
          const content = data.choices[0]?.message?.content;
          return res.json(JSON.parse(content));
        }
      } catch (apiErr) {
        console.warn('[AI] OpenAI request failed, falling back:', apiErr.message);
      }
    }

    if (geminiKey) {
      try {
        const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${geminiKey}`;
        const response = await fetch(url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents: [{ parts: [{ text: prompt }] }],
            generationConfig: {
              responseMimeType: 'application/json',
            },
          }),
        });

        if (response.ok) {
          const data = await response.json();
          const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
          return res.json(JSON.parse(text));
        }
      } catch (geminiErr) {
        console.warn('[AI] Gemini request failed, falling back:', geminiErr.message);
      }
    }

    // High quality offline fallback with curated authentic verses and empathy
    const fallback = generateFallbackResponse(prompt, response_json_schema);
    return res.json(fallback);
  } catch (err) {
    console.error('[AI] Handler error:', err);
    res.status(500).json({ error: 'LLM invocation failed', message: err.message });
  }
});

export default router;
